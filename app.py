# Hide Message Page
@app.route('/encode', methods=['GET', 'POST'])
def encode():

    if request.method == 'POST':

        image = request.files.get('image')
        message = request.form.get('message')
        password = request.form.get('password')

        if not image or not image.filename:
            return render_template('encode.html', error="Please select an image.")

        if not message or not password:
            return render_template('encode.html', error="Please enter a message and password.")

        if (
            len(password) < 8
            or not any(char.isupper() for char in password)
            or not any(char.islower() for char in password)
            or not any(char.isdigit() for char in password)
        ):
            return render_template(
                'encode.html',
                error="Password must contain at least 8 characters, including uppercase, lowercase and a number."
            )

        filename = secure_filename(image.filename)

        if not filename.lower().endswith(('.png', '.jpg', '.jpeg')):
            return render_template('encode.html', error="Only PNG and JPG images are allowed.")

        unique_id = uuid.uuid4().hex

        input_path = os.path.join(UPLOAD_FOLDER, unique_id + "_" + filename)
        output_path = os.path.join(OUTPUT_FOLDER, unique_id + "_encoded.png")

        image.save(input_path)

        if not validate_image(input_path):
            os.remove(input_path)
            return render_template(
                'encode.html',
                error="Invalid image file. Please upload a valid image."
            )

        try:
            encode_image(input_path, output_path, message, password)

            return render_template(
                'encode.html',
                success="Message hidden successfully!",
                download_file=unique_id + "_encoded.png"
            )

        except Exception:
            app.logger.exception("Image encoding failed")

            return render_template(
                'encode.html',
                error="Unable to hide the message. Please check your image and try again."
            )

        finally:
            if os.path.exists(input_path):
                os.remove(input_path)

    return render_template('encode.html')

@app.route('/download/<filename>')
def download(filename):

    # Allow only filenames generated by our website
    if not re.fullmatch(r'[a-f0-9]{32}_encoded\.png', filename):
        return "Invalid filename!", 400

    file_path = os.path.join(OUTPUT_FOLDER, filename)

    if not os.path.isfile(file_path):
        return "File not found!", 404

    response = send_from_directory(
        OUTPUT_FOLDER,
        filename,
        as_attachment=True,
        download_name="encoded_image.png"
    )

    # Delete the file after the response is closed
    def cleanup():
        try:
            if os.path.exists(file_path):
                os.remove(file_path)
        except OSError:
            pass

    response.call_on_close(cleanup)

    return response

# Extract Message Page
@app.route('/decode', methods=['GET', 'POST'])
def decode():

    if request.method == 'POST':

        image = request.files.get('image')
        password = request.form.get('password')

        if not image or not image.filename:
            return render_template('decode.html', error="Please select an image.")

        if not password:
            return render_template('decode.html', error="Please enter your password.")

        filename = secure_filename(image.filename)

        if not filename.lower().endswith('.png'):
            return render_template('decode.html', error="Please upload an encoded PNG image.")

        unique_id = uuid.uuid4().hex
        input_path = os.path.join(UPLOAD_FOLDER, unique_id + "_" + filename)

        image.save(input_path)

        if not validate_image(input_path):
            os.remove(input_path)
            return render_template(
                'decode.html',
                error="Invalid image file. Please upload a valid PNG image."
            )

        try:
            message = decode_image(input_path, password)

            return render_template('decode.html', message=message)

        except Exception:
            app.logger.exception("Message extraction failed")

            return render_template(
                'decode.html',
                error="Unable to extract the message. Please check your image and password."
            )

        finally:
            if os.path.exists(input_path):
                os.remove(input_path)

    return render_template('decode.html')


